import {readFile,writeFile} from 'node:fs/promises';
const product=JSON.parse(await readFile(new URL('../commerce/product.json',import.meta.url),'utf8'));
if(!Number.isInteger(product.amount)||product.amount<1||product.offlineGraceDays<1)throw Error('Invalid product');
await writeFile(new URL('../docs/iphone/access/product.mjs',import.meta.url),`// Generated by npm run build:commerce; edit commerce/product.json.\nexport default Object.freeze(${JSON.stringify(product,null,2)});\n`);
